// Voice to text (Groq Whisper) and text to voice (Kokoro on Replicate), run
// in the main process so the keys never reach the window. The Kokoro module
// and the hint-echo stripper are the Nirmanakaya Reader's own files, used
// unchanged from vendor/nkya-speech; the transcription call is the Reader's
// transcribe route without its Next.js wrapper.
const path = require("path");
const { pathToFileURL } = require("url");

const VENDOR = path.join(__dirname, "..", "..", "vendor", "nkya-speech");

// From the Reader's transcribe.route.js (production, 2026-10).
const GROQ_URL = "https://api.groq.com/openai/v1/audio/transcriptions";
const MODEL = "whisper-large-v3-turbo";
const HINT = "A question, spoken plainly. Punctuated, with capitals and full stops.";
const MAX_BYTES = 8 * 1024 * 1024;
// Whisper's own "this was probably not speech" score, averaged over segments.
const NO_SPEECH_LIMIT = 0.6;

let vendorPromise;
function loadVendor() {
  vendorPromise ||= Promise.all([
    import(pathToFileURL(path.join(VENDOR, "kokoro.js")).href),
    import(pathToFileURL(path.join(VENDOR, "transcribeEcho.js")).href),
  ]).then(([kokoro, echo]) => ({ ...kokoro, stripPromptEcho: echo.stripPromptEcho }));
  return vendorPromise;
}

/**
 * Transcribe one recorded utterance.
 * @param {Uint8Array} audio  a WAV file
 * @returns {Promise<{text:string, secs:number, heard:boolean}>}
 */
async function transcribe(audio, { key = process.env.GROQ_API_KEY, fetchFn = fetch } = {}) {
  if (!key) throw new Error("Voice input needs GROQ_API_KEY in screen-buddy/.env");
  if (!audio?.byteLength) return { text: "", secs: 0, heard: false };
  if (audio.byteLength > MAX_BYTES) throw new Error("That recording was too long");
  const { stripPromptEcho } = await loadVendor();

  const form = new FormData();
  form.append("file", new Blob([audio], { type: "audio/wav" }), "speech.wav");
  form.append("model", MODEL);
  form.append("response_format", "verbose_json");
  form.append("temperature", "0");
  form.append("prompt", HINT);

  const r = await fetchFn(GROQ_URL, { method: "POST", headers: { Authorization: `Bearer ${key}` }, body: form });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(`Transcription failed: ${j?.error?.message || r.status}`);

  const secs = Number(j.duration) || 0;
  const { text } = stripPromptEcho(String(j.text || "").trim(), HINT);
  const segs = Array.isArray(j.segments) ? j.segments : [];
  const noSpeech = segs.length ? segs.reduce((a, g) => a + (Number(g.no_speech_prob) || 0), 0) / segs.length : 0;
  if (!text || noSpeech > NO_SPEECH_LIMIT) return { text: "", secs, heard: false };
  return { text, secs, heard: true };
}

/**
 * Speaks reply pieces one after another. Each piece is generated by Kokoro,
 * downloaded, and handed to the window to play in order; generation of the
 * next piece overlaps playback of the current one. If Kokoro isn't set up or
 * fails, the piece is handed over as text for the window's free built-in voice.
 */
class Speaker {
  constructor({
    send, // (channel, payload) => void, to the window
    voice = "bm_george",
    token = process.env.REPLICATE_API_TOKEN,
    fetchFn = fetch,
    vendor = loadVendor,
  }) {
    this.send = send;
    this.voice = voice;
    this.token = token;
    this.fetchFn = fetchFn;
    this.vendor = vendor;
    this.queue = [];
    this.running = false;
    this.generation = 0;
    this.seq = 0;
    this.fellBack = false;
  }

  get usesKokoro() {
    return Boolean(this.token);
  }

  say(piece) {
    const text = String(piece || "").trim();
    if (!text) return;
    this.queue.push(text);
    if (!this.running) this._run();
  }

  // Stop now: drop what's queued; anything in flight is discarded when it lands.
  stop() {
    this.generation++;
    this.queue = [];
    this.send("voice:stop");
    if (!this.running) this.send("voice:tts-idle");
  }

  // Wake Kokoro so the first real sentence doesn't pay a cold start.
  async warm() {
    if (!this.usesKokoro) return;
    try {
      const { speakPiece } = await this.vendor();
      await speakPiece("Hi.", this.voice);
    } catch {
      // A failed warm-up only means the first sentence may be slower.
    }
  }

  async _run() {
    this.running = true;
    this.send("voice:tts-busy");
    const gen = this.generation;
    try {
      while (this.queue.length && gen === this.generation) {
        const text = this.queue.shift();
        const out = await this._make(text);
        if (gen !== this.generation) break;
        this.send("voice:play", { seq: this.seq++, ...out });
      }
    } finally {
      this.running = false;
      if (this.queue.length && gen !== this.generation) {
        this._run(); // something new was said after a stop
      } else {
        this.send("voice:tts-idle");
      }
    }
  }

  // -> { audio: Uint8Array, mime } or { text } for the built-in voice
  async _make(text) {
    if (!this.usesKokoro) return { text };
    try {
      const { speakPiece, forTheEar } = await this.vendor();
      const spoken = forTheEar(text);
      if (!spoken) return { text: "" };
      const { url } = await speakPiece(spoken, this.voice);
      if (!url) throw new Error("Kokoro returned no audio");
      const r = await this.fetchFn(url);
      if (!r.ok) throw new Error(`Couldn't download the voice clip (${r.status})`);
      const audio = new Uint8Array(await r.arrayBuffer());
      return { audio, mime: r.headers.get("content-type") || "audio/wav" };
    } catch (err) {
      if (!this.fellBack) {
        this.fellBack = true;
        this.send("buddy:status", { text: `George couldn't talk (${err.message}); using the built-in voice.` });
      }
      return { text };
    }
  }
}

module.exports = { transcribe, Speaker, loadVendor, HINT };
